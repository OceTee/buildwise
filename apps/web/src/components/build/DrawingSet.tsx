/** Height of the roof above a plan point, or null when no roof plane covers it. */
function roofZ(planes: [number, number, number][][], x: number, y: number): number | null {
  let best: number | null = null;
  for (const p of planes) {
    if (!inPoly(p, x, y)) continue;
    const [a, b, c] = p;
    const n = cross(sub(b!, a!), sub(c!, a!));
    if (Math.abs(n[2]) < 1e-9) continue; // vertical gable triangle
    const z = a![2] - (n[0] * (x - a![0]) + n[1] * (y - a![1])) / n[2];
    if (best === null || z > best) best = z;
  }
  return best;
}
type V3 = [number, number, number];
const sub = (p: V3, q: V3): V3 => [p[0] - q[0], p[1] - q[1], p[2] - q[2]];
const cross = (u: V3, v: V3): V3 => [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
function inPoly(p: [number, number, number][], x: number, y: number) {
  let inside = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [xi, yi] = p[i]!; const [xj, yj] = p[j]!;
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function section(d: Design): SheetInfo {
  const H = d.storeyHeightM;
  const cx = sectionX(d);
  const main = mainBlock(d);
  const blocks = d.blocks.filter((b) => b.kind === 'house' && cx > b.x && cx < b.x + b.w);
  const planes = roofPlanes(d);
  const o = d.roof.overhangM + 0.5;
  const cutEls = elementsOf(d).filter((e) => cx > e.x && cx < e.x + e.w && e.kind !== 'screen');
  const lo = Math.min(...blocks.map((b) => b.y), ...cutEls.map((e) => e.y)) - o; const hi = Math.max(...blocks.map((b) => b.y + b.d), ...cutEls.map((e) => e.y + e.d)) + o;
  const ridge = Math.max(d.storeys * H + d.slabM + (d.roof.kind === 'flat' ? d.roof.parapetM : 0), ...planes.flat().map((p) => p[2]));
  const scale = pickScale(hi - lo, ridge + 1.6 + 1, AREA.w, AREA.h - 20);
  const k = 1000 / scale;
  const ox = AREA.x + (AREA.w - (hi - lo) * k) / 2;
  const base = AREA.y + AREA.h - 26;
  const U = (y: number) => ox + (y - lo) * k; // street on the left
  const Z = (z: number) => base - z * k;
  const els: ReactNode[] = [];
  // Ground, foundations and slabs.
  els.push(<line key="g" x1={AREA.x + 4} x2={AREA.x + AREA.w - 4} y1={Z(0)} y2={Z(0)} stroke={INK} strokeWidth={0.6} />);
  for (const b of blocks) {
    for (let s = 0; s < b.storeys; s++) {
      const z0 = s === 0 ? 0 : s * H - d.slabM;
      els.push(<rect key={`s${b.id}${s}`} x={U(b.y) - 0.1 * k} y={Z(z0 + d.slabM)} width={(b.d + 0.2) * k} height={d.slabM * k} fill="#bbb" stroke={INK} strokeWidth={0.3} />);
    }
    if (d.roof.kind === 'flat') {
      const z = b.storeys * H;
      els.push(<rect key={`rs${b.id}`} x={U(b.y) - 0.1 * k} y={Z(z + d.slabM)} width={(b.d + 0.2) * k} height={d.slabM * k} fill="#bbb" stroke={INK} strokeWidth={0.3} />);
    }
  }
  // Walls cut by the section line (walls running across it), with the openings in them.
  for (const w of d.walls.filter((x) => x.dir === 'h' && cx > x.from && cx < x.to)) {
    const z0 = w.storey * H; const z1 = (w.storey + 1) * H;
    const op = d.openings.find((p) => p.dir === 'h' && p.storey === w.storey && Math.abs(p.at - w.at) < 1e-6 && cx > p.from && cx < p.to);
    const t = w.thickness;
    const part = (a: number, b: number, key: string) => b > a && els.push(<rect key={key} x={U(w.at - t / 2)} y={Z(b)} width={t * k} height={(b - a) * k} fill={INK} />);
    if (op) { part(z0 + d.slabM, z0 + op.sillM, `${w.id}a`); part(z0 + op.headM, z1, `${w.id}b`); }
    else part(z0 + (w.storey === 0 ? d.slabM : 0), z1, w.id);
    if (w.storey === 0 && w.external) {
      els.push(<rect key={`${w.id}f`} x={U(w.at) - 0.3375 * k} y={Z(-0.675)} width={0.675 * k} height={0.225 * k} fill="#999" stroke={INK} strokeWidth={0.25} />);
      els.push(<rect key={`${w.id}fw`} x={U(w.at - t / 2)} y={Z(0)} width={t * k} height={0.45 * k} fill="#555" />);
    }
  }
  // Roof line along the cut.
  if (d.roof.kind !== 'flat') {
    const pts: string[] = [];
    for (let y = lo; y <= hi; y += 0.05) { const z = roofZ(planes, cx, y); if (z !== null) pts.push(`${U(y)},${Z(z)}`); }
    if (pts.length > 1) els.push(<polyline key="roof" points={pts.join(' ')} fill="none" stroke={INK} strokeWidth={0.8} strokeLinejoin="round" />);
  }
  // Porches, balconies and canopies the line cuts: slabs and roofs cut solid, posts and rails beyond in outline.
  for (const e of cutEls) {
    for (const [i, b] of elementBoxes(d, e).entries()) {
      const cut = cx >= b.x0 && cx <= b.x1;
      if (!cut && b.part !== 'post') continue;
      const solid = cut && (b.part === 'roof' || b.part === 'slab' || b.part === 'floor' || b.part === 'clad' || b.part === 'beam');
      els.push(<rect key={`ce${e.id}${i}`} x={U(b.y0)} y={Z(b.z1)} width={Math.max((b.y1 - b.y0) * k, 0.12)} height={(b.z1 - b.z0) * k}
        fill={solid ? '#555' : b.part === 'rail' ? '#dbe9f0' : '#fff'} fillOpacity={b.part === 'rail' ? 0.6 : 1} stroke={INK} strokeWidth={cut ? 0.3 : 0.15} />);
    }
  }
  // Room names along the cut.
  for (const r of d.rooms.filter((x) => cx > x.x && cx < x.x + x.w && x.kind !== 'corridor' && blocks.some((b) => b.id === x.block))) {
    els.push(<text key={`n${r.id}`} x={U(r.y + r.d / 2)} y={Z(r.storey * H + H * 0.45)} fontSize={2} textAnchor="middle">{r.name.toUpperCase()}</text>);
  }
  const levels = [0.15, ...Array.from({ length: d.storeys - 1 }, (_, s) => (s + 1) * H), d.storeys * H];
  return {
    no: 'A-301', title: 'Section A–A', scale: `1:${scale}`,
    body: (
      <g>
        {els}
        {levels.map((z) => <Level key={z} x={AREA.x + 6} y={Z(z)} label={`${z === 0.15 ? 'FFL ' : ''}+${z.toFixed(3)}`} />)}
        {d.roof.kind !== 'flat' && <Level x={AREA.x + 6} y={Z(ridge)} label={`RIDGE +${ridge.toFixed(3)}`} />}
        <text x={AREA.x + AREA.w / 2} y={base + 14} fontSize={2.8} textAnchor="middle" fontWeight={700}>SECTION A–A THROUGH THE {main.name.toUpperCase()}</text>
        <text x={AREA.x + AREA.w / 2} y={base + 18.5} fontSize={2} textAnchor="middle" fill={FAINT}>Street side on the left. Foundations indicative: {fmt(0.675)} × {fmt(0.225)} strip at {fmt(0.9)} below ground, to be designed by the engineer.</text>
      </g>
    ),
  };
}

