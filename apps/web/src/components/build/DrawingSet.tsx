/**
 * A concept drawing set for one generated design, drawn as SVG on A3 landscape sheets in millimetres: site plan,
 * a floor plan per storey (walls, door swings, windows, furniture, dimensions), elevations and a section. Every
 * line comes from the same geometry the 3D view and the bill of materials use. Printing gives a PDF.
 * The design's architecture (`Design.elements`) is drawn too: dashed outlines on the site and floor plans (overhead
 * roofs dashed, columns solid), and porches, balconies, canopies, pergolas, screens and feature walls on the
 * elevations and the section, with floor-to-ceiling glazing shown as glass walls with their mullions.
 */

const A3 = { w: 420, h: 297 };
const M = 10;          // sheet margin
const TB = 78;         // title block width
const AREA = { x: M + 4, y: M + 4, w: A3.w - 2 * M - TB - 8, h: A3.h - 2 * M - 8 };
const SCALES = [50, 75, 100, 125, 150, 200, 250, 300, 400, 500];
const INK = '#111';
const FAINT = '#8a8a8a';

const mm = (m: number) => Math.round(m * 1000);
const fmt = (m: number) => mm(m).toLocaleString('en').replace(/,/g, ' ');
const pickScale = (wM: number, hM: number, w = AREA.w, h = AREA.h) => SCALES.find((s) => (wM * 1000) / s <= w && (hM * 1000) / s <= h) ?? 500;

interface SheetInfo { no: string; title: string; scale: string; body: ReactNode }

export function DrawingSet({ design, name = design.name, project, date, landscape = null }: { design: Design; /** The design's own name (its concept title). */ name?: string; project: string; date: string; landscape?: Landscape | null }) {
  const sheets: SheetInfo[] = [sitePlan(design, landscape)];
  for (let s = 0; s < design.storeys; s++) sheets.push(floorPlan(design, s));
  sheets.push(elevations(design), section(design));
  return (
    <div className="drawing-set">
      {sheets.map((s) => <Sheet key={s.no} sheet={s} design={design} name={name} project={project} date={date} />)}
    </div>
  );
}

