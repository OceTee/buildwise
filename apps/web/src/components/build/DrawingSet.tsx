/** Naive word wrap for SVG text (about 0.5 em per character). */
function Wrapped({ x, y, width, size, text }: { x: number; y: number; width: number; size: number; text: string }) {
  const per = Math.floor(width / (size * 0.5));
  const lines: string[] = [];
  let cur = '';
  for (const w of text.split(' ')) { if ((cur + ' ' + w).trim().length > per) { lines.push(cur.trim()); cur = w; } else cur += ' ' + w; }
  if (cur.trim()) lines.push(cur.trim());
  return <text x={x} y={y} fontSize={size} fill="#333">{lines.map((l, i) => <tspan key={i} x={x} dy={i ? size * 1.35 : 0}>{l}</tspan>)}</text>;
}

// ---------------------------------------------------------------- plan frame

/** Maps plan metres to sheet millimetres: x to the right, the street (y = 0) at the bottom. */
function planFrame(minX: number, minY: number, maxX: number, maxY: number, scale: number, box = AREA) {
  const k = 1000 / scale;
  const ox = box.x + (box.w - (maxX - minX) * k) / 2;
  const oy = box.y + (box.h - (maxY - minY) * k) / 2;
  return { k, X: (x: number) => ox + (x - minX) * k, Y: (y: number) => oy + (maxY - y) * k };
}

function Dim({ x1, y1, x2, y2, label, off, k }: { x1: number; y1: number; x2: number; y2: number; label: string; off: number; k: number }) {
  // Horizontal or vertical dimension line, offset from the measured points, with architectural ticks.
  const h = Math.abs(y1 - y2) < 1e-6;
  const [ax, ay, bx, by] = h ? [x1, y1 + off, x2, y2 + off] : [x1 + off, y1, x2 + off, y2];
  const t = 1.2;
  const fs = Math.max(1.8, Math.min(2.6, k * 0.25));
  return (
    <g stroke={INK} strokeWidth={0.18}>
      <line x1={x1} y1={y1} x2={ax} y2={ay} stroke={FAINT} />
      <line x1={x2} y1={y2} x2={bx} y2={by} stroke={FAINT} />
      <line x1={ax} y1={ay} x2={bx} y2={by} />
      <line x1={ax - t / 2} y1={ay + t / 2} x2={ax + t / 2} y2={ay - t / 2} strokeWidth={0.35} />
      <line x1={bx - t / 2} y1={by + t / 2} x2={bx + t / 2} y2={by - t / 2} strokeWidth={0.35} />
      <text x={(ax + bx) / 2} y={(ay + by) / 2 - 0.8} fontSize={fs} stroke="none" textAnchor="middle"
        transform={h ? undefined : `rotate(-90 ${(ax + bx) / 2} ${(ay + by) / 2})`}>{label}</text>
    </g>
  );
}

/** A dimension chain: one line split at every break point, plus the overall length. */
function chain(points: number[], fixed: number, dir: 'h' | 'v', off: number, f: ReturnType<typeof planFrame>, key: string): ReactNode[] {
  const ps = [...new Set(points.map((p) => Math.round(p * 1000)))].sort((a, b) => a - b).map((p) => p / 1000);
  const out: ReactNode[] = [];
  for (let i = 0; i + 1 < ps.length; i++) {
    const a = ps[i]!; const b = ps[i + 1]!;
    if (b - a < 0.25) continue;
    out.push(dir === 'h'
      ? <Dim key={`${key}${i}`} x1={f.X(a)} y1={f.Y(fixed)} x2={f.X(b)} y2={f.Y(fixed)} off={off} label={fmt(b - a)} k={f.k} />
      : <Dim key={`${key}${i}`} x1={f.X(fixed)} y1={f.Y(a)} x2={f.X(fixed)} y2={f.Y(b)} off={off} label={fmt(b - a)} k={f.k} />);
  }
  return out;
}

