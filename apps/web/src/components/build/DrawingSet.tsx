// ---------------------------------------------------------------- A-101/102 floor plans

function floorPlan(d: Design, storey: number): SheetInfo {
  // The house fills the sheet; a detached outbuilding gets its own inset at the same scale, so it never shrinks the plan.
  const house = d.blocks.filter((b) => b.kind === 'house' && b.storeys > storey);
  const outs = d.blocks.filter((b) => b.kind === 'outbuilding' && b.storeys > storey);
  const near = (bs: typeof house) => elementsOnPlan(d, storey).filter((e) => bs.some((b) => e.x <= b.x + b.w + 0.3 && e.x + e.w >= b.x - 0.3 && e.y <= b.y + b.d + 0.3 && e.y + e.d >= b.y - 0.3));
  const ext = (bs: typeof house) => {
    const rs = [...bs, ...near(bs)];
    return { minX: Math.min(...rs.map((b) => b.x)) - 2.5, maxX: Math.max(...rs.map((b) => b.x + b.w)) + 2.5, minY: Math.min(...rs.map((b) => b.y)) - 2.5, maxY: Math.max(...rs.map((b) => b.y + b.d)) + 2.5 };
  };
  const he = ext(house);
  const inset = outs.length ? ext(outs) : null;
  const insetW = inset ? Math.min(110, AREA.w * 0.32) : 0;
  const mainBox = { ...AREA, x: AREA.x + insetW, w: AREA.w - insetW };
  let scale = pickScale(he.maxX - he.minX, he.maxY - he.minY, mainBox.w, mainBox.h);
  if (inset) scale = Math.max(scale, pickScale(inset.maxX - inset.minX, inset.maxY - inset.minY, insetW - 6, AREA.h * 0.45));
  const f = planFrame(he.minX, he.minY, he.maxX, he.maxY, scale, mainBox);
  const els: ReactNode[] = [drawPlan(d, storey, house, f, 'h')];
  if (inset) {
    const fi = planFrame(inset.minX, inset.minY, inset.maxX, inset.maxY, scale, { x: AREA.x + 2, y: AREA.y + 8, w: insetW - 6, h: AREA.h * 0.45 });
    els.push(
      <g key="inset">
        <text x={AREA.x + 4} y={AREA.y + 4} fontSize={2.4} fontWeight={700}>{outs.map((b) => b.name.toUpperCase()).join(', ')} (DETACHED, AT THE BACK)</text>
        {drawPlan(d, storey, outs, fi, 'o')}
      </g>,
    );
  }
  els.push(<text key="street" x={mainBox.x + mainBox.w / 2} y={AREA.y + AREA.h - 1} fontSize={2.4} textAnchor="middle" fill={FAINT} letterSpacing={1}>STREET SIDE</text>);
  const names = ['Ground', 'First', 'Second', 'Third'];
  return { no: `A-${101 + storey}`, title: `${names[storey] ?? `Level ${storey}`} floor plan`, scale: `1:${scale}`, body: <g>{els}</g> };
}

/** Plan of the given blocks on one storey: floors, furniture, walls, openings, labels, dimensions, section line. */
function drawPlan(d: Design, storey: number, blocks: Design['blocks'], f: ReturnType<typeof planFrame>, kp: string): ReactNode {
  const ids = new Set(blocks.map((b) => b.id));
  const rooms = d.rooms.filter((r) => r.storey === storey && ids.has(r.block));
  const inBlocks = (x: number, y: number) => blocks.some((b) => x >= b.x - 0.3 && x <= b.x + b.w + 0.3 && y >= b.y - 0.3 && y <= b.y + b.d + 0.3);
  const walls = d.walls.filter((w) => w.storey === storey && (w.dir === 'h' ? inBlocks((w.from + w.to) / 2, w.at) : inBlocks(w.at, (w.from + w.to) / 2)));
  const ops = d.openings.filter((o) => o.storey === storey && rooms.some((r) => r.id === o.roomId));
  const els: ReactNode[] = [];

  // Floors: wet rooms tinted, the rest white.
  for (const r of rooms) els.push(<rect key={`f${r.id}`} x={f.X(r.x)} y={f.Y(r.y + r.d)} width={r.w * f.k} height={r.d * f.k} fill={WET.has(r.kind) ? '#eef3f7' : r.kind === 'corridor' ? '#fafafa' : '#fff'} />);
  for (const item of furnishFloor(d, storey).filter((object) => rooms.some((r) => r.id === object.roomId))) {
    const x = f.X(item.x); const y = f.Y(item.y + item.d);
    const w = item.w * f.k; const h = item.d * f.k;
    els.push(<g key={item.id} fill="none" stroke="#898989" strokeWidth={0.2}>
      <rect x={x} y={y} width={w} height={h} rx={0.25} />
      {item.kind === 'bed' && (item.turn
        ? <line x1={x + w * 0.83} x2={x + w * 0.83} y1={y} y2={y + h} />
        : <line x1={x} x2={x + w} y1={y + h * 0.83} y2={y + h * 0.83} />)}
      {item.kind === 'dining-table' && <rect x={x + w * 0.18} y={y + h * 0.2} width={w * 0.64} height={h * 0.6} rx={0.2} />}
      {item.kind === 'shower' && <line x1={x} x2={x + w} y1={y} y2={y + h} />}
    </g>);
  }
  for (const r of rooms.filter((room) => room.kind === 'stair')) els.push(<g key={`u${r.id}`}>{stairSymbol(r, f)}</g>);

  // Architecture outside the walls: porches, verandas, pergolas and canopies on the ground floor, balconies on their floor,
  // screens and feature walls on every floor they reach (dashed where overhead or projecting).
  const touches = (e: ArchElement) => blocks.some((b) => e.x <= b.x + b.w + 0.3 && e.x + e.w >= b.x - 0.3 && e.y <= b.y + b.d + 0.3 && e.y + e.d >= b.y - 0.3);
  const planEls = elementsOnPlan(d, storey).filter(touches);
  for (const e of planEls) els.push(planElement(d, e, f, storey, `pe${e.id}`));
  // The columns at a loggia's open corners.
  for (const [i, c] of loggiaColumns(d).filter((x) => x.storey === storey).entries()) els.push(<rect key={`lc${i}`} x={f.X(c.x - c.size / 2)} y={f.Y(c.y + c.size / 2)} width={c.size * f.k} height={c.size * f.k} fill={INK} />);

  // Walls, cut around their openings.
  for (const w of walls) {
    const cuts = ops.filter((o) => o.dir === w.dir && Math.abs(o.at - w.at) < 1e-6 && o.from >= w.from - 1e-6 && o.to <= w.to + 1e-6).sort((a, b) => a.from - b.from);
    let cur = w.from;
    const seg = (a: number, b: number, i: number) => {
      if (b - a < 0.01) return;
      const t = w.thickness;
      els.push(w.dir === 'h'
        ? <rect key={`${w.id}-${i}`} x={f.X(a - (a === w.from ? t / 2 : 0))} y={f.Y(w.at + t / 2)} width={(b - a + (a === w.from ? t / 2 : 0) + (b === w.to ? t / 2 : 0)) * f.k} height={t * f.k} fill={w.external ? INK : '#444'} />
        : <rect key={`${w.id}-${i}`} x={f.X(w.at - t / 2)} y={f.Y(b + (b === w.to ? t / 2 : 0))} width={t * f.k} height={(b - a + (a === w.from ? t / 2 : 0) + (b === w.to ? t / 2 : 0)) * f.k} fill={w.external ? INK : '#444'} />);
    };
    cuts.forEach((o, i) => { seg(cur, o.from, i); cur = o.to; });
    seg(cur, w.to, cuts.length);
  }

  // Openings: windows as glazing lines in the wall, doors as a leaf and swing arc into the room they serve.
  for (const o of ops) {
    const w = walls.find((x) => x.dir === o.dir && Math.abs(x.at - o.at) < 1e-6 && o.from >= x.from - 1e-6 && o.to <= x.to + 1e-6);
    const t = w?.thickness ?? 0.2;
    if (o.kind === 'window') {
      els.push(o.dir === 'h'
        ? <g key={o.id} stroke={INK} strokeWidth={0.2}><rect x={f.X(o.from)} y={f.Y(o.at + t / 2)} width={(o.to - o.from) * f.k} height={t * f.k} fill="#fff" />{[-t / 6, t / 6].map((dy) => <line key={dy} x1={f.X(o.from)} x2={f.X(o.to)} y1={f.Y(o.at + dy)} y2={f.Y(o.at + dy)} />)}</g>
        : <g key={o.id} stroke={INK} strokeWidth={0.2}><rect x={f.X(o.at - t / 2)} y={f.Y(o.to)} width={t * f.k} height={(o.to - o.from) * f.k} fill="#fff" />{[-t / 6, t / 6].map((dx) => <line key={dx} y1={f.Y(o.from)} y2={f.Y(o.to)} x1={f.X(o.at + dx)} x2={f.X(o.at + dx)} />)}</g>);
      continue;
    }
    if (o.passage === 'open') continue;
    if (o.passage === 'arch') {
      const mid = (o.from + o.to) / 2;
      const x = f.X(o.dir === 'h' ? mid : o.at);
      const y = f.Y(o.dir === 'h' ? o.at : mid);
      els.push(<text key={o.id} x={x} y={y - 0.45} fontSize={1.55} textAnchor="middle" fill={INK}
        transform={o.dir === 'v' ? `rotate(-90 ${x} ${y})` : undefined}>ARCH</text>);
      continue;
    }
    const room = rooms.find((r) => r.id === o.roomId);
    // Each hinged leaf swings into the room it serves.
    const sign = !room ? 1 : o.dir === 'h' ? (Math.abs(room.y - o.at) < 1e-6 ? 1 : -1) : (Math.abs(room.x - o.at) < 1e-6 ? 1 : -1);
    const mid = (o.from + o.to) / 2;
    const leaves = o.passage === 'double' ? [[o.from, mid], [o.to, mid]] as const : [[o.from, o.to]] as const;
    els.push(<g key={o.id} stroke={INK} fill="none">{leaves.map(([hinge, closed]) => {
      const len = Math.abs(closed - hinge);
      const across = o.at + (sign * t) / 2;
      const swing = across + sign * len;
      const [hx, hy, sx, sy, cx, cy] = o.dir === 'h'
        ? [f.X(hinge), f.Y(across), f.X(hinge), f.Y(swing), f.X(closed), f.Y(across)]
        : [f.X(across), f.Y(hinge), f.X(swing), f.Y(hinge), f.X(across), f.Y(closed)];
      const sweep = (o.dir === 'h' ? sign : -sign) * Math.sign(closed - hinge) > 0 ? 1 : 0;
      return <g key={hinge}>
        <line x1={hx} y1={hy} x2={sx} y2={sy} strokeWidth={0.35} />
        <path d={`M ${sx} ${sy} A ${len * f.k} ${len * f.k} 0 0 ${sweep} ${cx} ${cy}`} strokeWidth={0.15} strokeDasharray="0.8 0.6" />
      </g>;
    })}</g>);
  }

  // Room labels.
  const fs = Math.max(1.7, Math.min(2.6, f.k * 0.22));
  for (const r of rooms.filter((x) => x.kind !== 'corridor' || x.w * x.d > 6)) {
    const cx = f.X(r.x + r.w / 2); const cy = f.Y(r.y + r.d / 2);
    els.push(
      <g key={`l${r.id}`} textAnchor="middle">
        <text x={cx} y={cy - fs * 0.2} fontSize={fs} fontWeight={700}>{r.name.toUpperCase()}</text>
        {r.kind !== 'corridor' && <text x={cx} y={cy + fs * 1.05} fontSize={fs * 0.82}>{(r.w * r.d).toFixed(1)} m² · {r.w.toFixed(1)} × {r.d.toFixed(1)}</text>}
      </g>,
    );
  }

  // Dimensions: per block, a room chain and an overall line on the street side and on the left.
  blocks.forEach((b, i) => {
    // Dimension the free side: if another wing is attached in front (or on the left), use the rear (or right).
    const ov = (a0: number, a1: number, b0: number, b1: number) => Math.min(a1, b1) - Math.max(a0, b0) > 0.3;
    const frontBusy = blocks.some((o) => o !== b && Math.abs(o.y + o.d - b.y) < 1e-6 && ov(o.x, o.x + o.w, b.x, b.x + b.w));
    const leftBusy = blocks.some((o) => o !== b && Math.abs(o.x + o.w - b.x) < 1e-6 && ov(o.y, o.y + o.d, b.y, b.y + b.d));
    const hy = frontBusy ? b.y + b.d : b.y; const hs = frontBusy ? -1 : 1;
    const vx = leftBusy ? b.x + b.w : b.x; const vs = leftBusy ? 1 : -1;
    const along = rooms.filter((r) => Math.abs((frontBusy ? r.y + r.d : r.y) - hy) < 1e-6 && r.x >= b.x - 1e-6 && r.x + r.w <= b.x + b.w + 1e-6);
    const side = rooms.filter((r) => Math.abs((leftBusy ? r.x + r.w : r.x) - vx) < 1e-6 && r.y >= b.y - 1e-6 && r.y + r.d <= b.y + b.d + 1e-6);
    // Dimension lines clear anything projecting on that side (a porch, a balcony).
    const proj = (side: 'h' | 'v') => Math.max(0, ...planEls.map((e) => side === 'h'
      ? (frontBusy ? e.y + e.d - (b.y + b.d) : b.y - e.y) * (e.x < b.x + b.w && e.x + e.w > b.x ? 1 : 0)
      : (leftBusy ? e.x + e.w - (b.x + b.w) : b.x - e.x) * (e.y < b.y + b.d && e.y + e.d > b.y ? 1 : 0))) * f.k;
    const ph = proj('h'); const pv = proj('v');
    els.push(...chain(along.flatMap((r) => [r.x, r.x + r.w]), hy, 'h', (5 + ph) * hs, f, `cf${i}`));
    els.push(<Dim key={`of${i}`} x1={f.X(b.x)} y1={f.Y(hy)} x2={f.X(b.x + b.w)} y2={f.Y(hy)} off={(10 + ph) * hs} label={fmt(b.w)} k={f.k} />);
    els.push(...chain(side.flatMap((r) => [r.y, r.y + r.d]), vx, 'v', (5 + pv) * vs, f, `cl${i}`));
    els.push(<Dim key={`ol${i}`} x1={f.X(vx)} y1={f.Y(b.y)} x2={f.X(vx)} y2={f.Y(b.y + b.d)} off={(10 + pv) * vs} label={fmt(b.d)} k={f.k} />);
  });

  // Section line A–A through the main block.
  const main = mainBlock(d);
  if (ids.has(main.id) && main.storeys > storey) {
    const cx = sectionX(d);
    els.push(
      <g key="sec" stroke={INK} strokeWidth={0.4}>
        <line x1={f.X(cx)} y1={f.Y(main.y - 1.6)} x2={f.X(cx)} y2={f.Y(main.y + main.d + 1.6)} strokeDasharray="5 1.2 1 1.2" strokeWidth={0.25} />
        {[main.y - 1.6, main.y + main.d + 1.6].map((y) => (
          <g key={y}><circle cx={f.X(cx)} cy={f.Y(y)} r={2.4} fill="#fff" /><text x={f.X(cx)} y={f.Y(y) + 1} fontSize={2.6} textAnchor="middle" stroke="none" fontWeight={700}>A</text></g>
        ))}
      </g>,
    );
  }
  return <g key={kp}>{els.map((e, i) => <g key={`${kp}${i}`}>{e}</g>)}</g>;
}

